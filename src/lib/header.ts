/**
 * То, что должны знать про шапку и прокрутка, и сама шапка.
 *
 * Шапка липкая и прячется при движении вниз, поэтому «отступ под шапку»
 * зависит от направления прыжка: вниз она уезжает сама и место под неё
 * резервировать не нужно, вверх — возвращается и закрыла бы заголовок.
 */

/** До этой отметки шапка не прячется: на первом экране она нужна всегда */
export const HEADER_HIDE_AFTER = 120;

/**
 * Высота шапки в пикселях. Меряем живой элемент, а не константу.
 *
 * Воздуха сверх высоты не добавляем: у секции есть собственный внутренний отступ,
 * а лишние пиксели показывали бы над ней полоску предыдущей секции.
 */
export function headerOffset(): number {
  const height = document.querySelector("header")?.getBoundingClientRect().height ?? 0;
  return Math.ceil(height);
}
